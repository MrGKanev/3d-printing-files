"""Builds all models: models/*/model.py -> STL + per-model README.md + root README.

Usage: .venv/bin/python tools/build.py
model.py must define `parts` = {name: build123d Part}; info.toml describes the print.
"""
import runpy
import tomllib
from pathlib import Path

from build123d import export_stl

ROOT = Path(__file__).resolve().parent.parent
BED = 256  # Centauri Carbon, mm

HEADER = """# 3d-printing-files

Models for the **Elegoo Centauri Carbon** (Orca Slicer), made with [build123d](https://github.com/gumyr/build123d).

## Models

| Model | Version | Description | Material | Size (mm) | Status |
|---|---|---|---|---|---|
"""
FOOTER = """
## Usage

```
/opt/homebrew/bin/python3.12 -m venv .venv && .venv/bin/pip install build123d   # once
.venv/bin/python tools/build.py   # regenerates the STL files and all READMEs
```

New model: `models/<name>/model.py` (defines `part`) + `info.toml` (copy an existing one), then run `build.py`.
Open the `.stl` in Orca. The README files are generated - don't edit them by hand.
"""


def model_readme(info, files, sizes, vol):
    notes = "\n".join(f"- {n}" for n in info.get("notes", []))
    changes = "\n".join(f"- {c}" for c in info.get("changelog", []))
    return f"""# {info['name']}

{info['summary']}

**Version:** {info['version']} · **Status:** {info['status']}

| | |
|---|---|
| Files | {files} |
| Size | {sizes} mm |
| Volume | {vol / 1000:.1f} cm³ |
| Printer | {info['printer']} |
| Material | {info['material']} |
| Layer height | {info['layer_height']} |
| Walls | {info['walls']} |
| Infill | {info['infill']} |
| Support | {info['supports']} |
| Orientation | {info['orientation']} |
| Hardware | {', '.join(info.get('hardware', [])) or '-'} |
| License | {info.get('license', '-')} |

## Notes
{notes}

## Changelog
{changes}

Credit: {info.get('credit', '-')}

Source: [`model.py`](model.py) (parameters are at the top). Generated by `tools/build.py`.
"""


rows = []
for mdir in sorted((ROOT / "models").iterdir()):
    if not (mdir / "model.py").exists():
        continue
    info = tomllib.loads((mdir / "info.toml").read_text())
    parts = runpy.run_path(str(mdir / "model.py"))["parts"]
    files, sizes, vol = [], [], 0
    for name, part in parts.items():
        assert part.is_valid and len(part.solids()) == 1, f"{mdir.name}/{name}: invalid or multi-solid model"
        bb = part.bounding_box().size
        assert max(bb.X, bb.Y, bb.Z) <= BED, f"{mdir.name}/{name}: does not fit in {BED} mm"
        stl = f"{mdir.name}-{name}.stl"
        export_stl(part, str(mdir / stl))
        files.append(f"[`{stl}`]({stl})")
        sizes.append(f"{name} {bb.X:.0f} x {bb.Y:.0f} x {bb.Z:.0f}")
        vol += part.volume
    files, sizes = ", ".join(files), "; ".join(sizes)
    (mdir / "README.md").write_text(model_readme(info, files, sizes, vol))
    rows.append(f"| [{info['name']}](models/{mdir.name}/) | {info['version']} | {info['summary']} | {info['material']} | {sizes} | {info['status']} |\n")
    print(f"ok {mdir.name}: {sizes} mm, {vol / 1000:.1f} cm³")

(ROOT / "README.md").write_text(HEADER + "".join(rows) + FOOTER)
