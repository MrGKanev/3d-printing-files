"""Builds all models: models/*/model.py -> STL + per-model README.md + root README.

Usage: .venv/bin/python tools/build.py
model.py must define `part` (build123d); info.toml describes the print.
"""
import runpy
import tomllib
from pathlib import Path

from build123d import export_stl

ROOT = Path(__file__).resolve().parent.parent
BED = 256  # Centauri Carbon, mm

HEADER = """# 3d-printing-files

Models for the **Elegoo Centauri Carbon** (Orca Slicer), made with [build123d](https://github.com/gumyr/build123d).

## Models

| Model | Description | Material | Size (mm) | Status |
|---|---|---|---|---|
"""
FOOTER = """
## Usage

```
/opt/homebrew/bin/python3.12 -m venv .venv && .venv/bin/pip install build123d   # once
.venv/bin/python tools/build.py   # regenerates the STL files and all READMEs
```

New model: `models/<name>/model.py` (defines `part`) + `info.toml` (copy an existing one), then run `build.py`.
Open the `.stl` in Orca. The README files are generated - don't edit them by hand.
"""


def model_readme(info, stl, size, vol):
    notes = "\n".join(f"- {n}" for n in info.get("notes", []))
    return f"""# {info['name']}

{info['summary']}

**Status:** {info['status']}

| | |
|---|---|
| File | [`{stl}`]({stl}) |
| Size | {size} mm |
| Volume | {vol / 1000:.1f} cm³ |
| Printer | {info['printer']} |
| Material | {info['material']} |
| Layer height | {info['layer_height']} |
| Walls | {info['walls']} |
| Infill | {info['infill']} |
| Support | {info['supports']} |
| Orientation | {info['orientation']} |

## Notes
{notes}

Source: [`model.py`](model.py) (parameters are at the top). Generated by `tools/build.py`.
"""


rows = []
for mdir in sorted((ROOT / "models").iterdir()):
    if not (mdir / "model.py").exists():
        continue
    info = tomllib.loads((mdir / "info.toml").read_text())
    part = runpy.run_path(str(mdir / "model.py"))["part"]
    assert part.is_valid and len(part.solids()) == 1, f"{mdir.name}: invalid or multi-solid model"
    bb = part.bounding_box().size
    assert max(bb.X, bb.Y, bb.Z) <= BED, f"{mdir.name}: does not fit in {BED} mm"
    stl = f"{mdir.name}.stl"
    export_stl(part, str(mdir / stl))
    size = f"{bb.X:.0f} x {bb.Y:.0f} x {bb.Z:.0f}"
    (mdir / "README.md").write_text(model_readme(info, stl, size, part.volume))
    rows.append(f"| [{info['name']}](models/{mdir.name}/) | {info['summary']} | {info['material']} | {size} | {info['status']} |\n")
    print(f"ok {mdir.name}: {size} mm, {part.volume / 1000:.1f} cm³")

(ROOT / "README.md").write_text(HEADER + "".join(rows) + FOOTER)
